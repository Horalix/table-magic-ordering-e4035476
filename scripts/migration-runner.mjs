/**
 * Writes docs/migration-runner.sql: the pending migrations, applied without
 * anyone copying them.
 *
 * Lovable cannot run a file from disk; it retypes SQL into its database tool,
 * and 26 files (735 KB) cannot be retyped exactly — it said so and stopped.
 * Here the database fetches each file itself from this (public) repository at
 * a pinned commit, through pg_net, and a block runs a file only when the MD5
 * of what arrived equals the MD5 of the file as committed. All anyone types
 * is a few short blocks: a slip in one, a wrong file or a changed download
 * fails before anything runs, and each block runs one whole file in one
 * transaction, exactly as the migration tool would.
 *
 *   node scripts/migration-runner.mjs [--from 20261024130000] [--commit <sha>]
 *
 * --from    first file not yet applied on production (default below)
 * --commit  commit to fetch from (default: the latest commit that changed
 *           supabase/migrations; it must be pushed)
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs', 'migration-runner.sql');
const args = process.argv.slice(2);
const arg = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const git = (...a) => execFileSync('git', a, { cwd: ROOT, encoding: 'utf8' }).trim();

const FROM = arg('--from') ?? '20261024130000';
const commit = arg('--commit') ?? git('log', '-1', '--format=%H', '--', 'supabase/migrations');
const remote = git('remote', 'get-url', 'origin').match(/github\.com[/:]([^/]+\/[^/.]+)/)?.[1];
if (!remote) throw new Error('origin is not a GitHub repository');
if (!git('branch', '-r', '--contains', commit)) throw new Error(`${commit} is not pushed; push it first`);

const files = git('ls-tree', '--name-only', commit, 'supabase/migrations/')
  .split('\n').map((p) => path.basename(p))
  .filter((f) => f.endsWith('.sql') && f >= FROM).sort();
if (!files.length) throw new Error(`no migrations from ${FROM} at ${commit}`);

const pinned = files.map((file, i) => {
  const bytes = execFileSync('git', ['show', `${commit}:supabase/migrations/${file}`], { cwd: ROOT });
  if (bytes.includes(13)) throw new Error(`${file} has CR characters at ${commit}`);
  return { n: i + 1, file, md5: createHash('md5').update(bytes).digest('hex'), kb: Math.round(bytes.length / 1024) };
});
const N = pinned.length;
const base = `https://raw.githubusercontent.com/${remote}/${commit}/supabase/migrations`;

const block = ({ n, file, md5, kb }) => `-- ---- ${n} of ${N}: ${file} (${kb} KB)
DO $apply$
DECLARE v_sql text;
BEGIN
  SELECT r.content INTO v_sql
    FROM net._http_response r
   WHERE r.status_code = 200 AND md5(r.content) = '${md5}'
   ORDER BY r.created DESC
   LIMIT 1;
  IF v_sql IS NULL THEN
    RAISE EXCEPTION '${file} has not arrived exactly (md5 ${md5}); run step 1 again';
  END IF;
  EXECUTE v_sql;
  RAISE NOTICE 'applied ${file}';
END $apply$;
`;

const sql = `-- Apply the pending migrations without copying them.
-- Generated by \`node scripts/migration-runner.mjs\` — do not edit by hand.
--
-- ${N} files, ${pinned[0].file} to ${pinned[N - 1].file},
-- fetched from ${remote} at commit ${commit}.
--
-- The database downloads each file itself (pg_net) and runs it only when the
-- MD5 of what arrived equals the MD5 of the file as committed, pinned below.
-- A typing slip in a block, a wrong file or a changed download fails before
-- anything runs. Each block in step 3 runs one whole file in one transaction.
--
-- Run each step as its own query, in order. In step 3, run ONE block per
-- query, in order, and stop at the first error.

-- ===== Step 0: pg_net is installed (expect one row). If there is no row, run
-- CREATE EXTENSION IF NOT EXISTS pg_net; once and repeat this query.
SELECT extname, extversion FROM pg_extension WHERE extname = 'pg_net';

-- ===== Step 1: queue the downloads (expect ${N} rows). They are sent once this
-- query has committed; give them a few seconds.
SELECT f.file,
       net.http_get(url := '${base}/' || f.file, timeout_milliseconds := 60000) AS request_id
  FROM unnest(ARRAY[
${pinned.map((p) => `    '${p.file}'`).join(',\n')}
  ]) WITH ORDINALITY AS f(file, n)
 ORDER BY f.n;

-- ===== Step 2: every file arrived byte for byte (expect ${N} rows, all true).
-- A false row: wait a few seconds and repeat; still false, run step 1 again.
SELECT f.n, f.file,
       EXISTS (SELECT 1 FROM net._http_response r
                WHERE r.status_code = 200 AND md5(r.content) = f.md5) AS arrived_exactly
  FROM (VALUES
${pinned.map((p) => `    (${p.n}, '${p.file}', '${p.md5}')`).join(',\n')}
  ) AS f(n, file, md5)
 ORDER BY f.n;

-- ===== Step 3: apply, one block per query, in this order.

${pinned.map(block).join('\n')}`;

writeFileSync(OUT, sql);
console.log(`  ✓ ${N} files, ${pinned[0].file} … ${pinned[N - 1].file}, at ${commit.slice(0, 7)} → ${path.relative(ROOT, OUT)}`);
