#!/usr/bin/env node
/**
 * Vera Italia's house pairings as SQL.
 *
 *   node scripts/vera-italia/pairings-sql.mjs
 *
 * The pairings are kept in menu.json beside this file, under "pairings": a
 * section of the menu, the dish (by slug) a waiter would suggest with it, the
 * kind of suggestion, a priority (0–100) and why. menu.json stays the one
 * place Vera Italia's dishes are written down; this turns its pairings into
 * the generated block of supabase/migrations/20261031090000_vera_suggestions.sql,
 * by fixed id only — La Soul has sections and dishes of the same names, so
 * nothing is ever looked up by name in the database.
 *
 * Run it only while that migration is unapplied (supabase/tests/vera-suggestions.test.ts
 * fails if the block and menu.json disagree). Once it is live, a pairing is
 * changed in Admin → Service & suggestions, or with a new migration.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
export const MIGRATION = join(ROOT, 'supabase', 'migrations', '20261031090000_vera_suggestions.sql');
export const BEGIN = '-- BEGIN GENERATED by scripts/vera-italia/pairings-sql.mjs from scripts/vera-italia/menu.json';
export const END = '-- END GENERATED';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
/** What a pairing may be; 'after_meal' needs no section and 'alternative' is not a pairing. */
const TYPES = new Set(['pair_with', 'add_on', 'upgrade_to']);

/** A comment may say anything but end itself early. */
const comment = (s) => String(s).replace(/[\r\n]+/g, ' ');

/** The generated block, BEGIN to END, for the pairings in `menu`. */
export function pairingsSql(menu) {
  const sections = new Map();
  const dishes = new Map();
  for (const c of menu.categories) {
    for (const s of c.sections) {
      if (sections.has(s.name)) throw new Error(`two sections named "${s.name}" in menu.json`);
      sections.set(s.name, s);
      for (const it of s.items) dishes.set(it.slug, { ...it, section: s });
    }
  }

  const seen = new Set();
  const rows = (menu.pairings ?? []).map((p) => {
    const where = `pairing ${p.id ?? '(no id)'}`;
    if (!UUID.test(p.id ?? '') || seen.has(p.id)) throw new Error(`${where}: needs its own fixed id`);
    seen.add(p.id);
    const section = sections.get(p.with);
    if (!section) throw new Error(`${where}: no section "${p.with}" on the menu`);
    const dish = dishes.get(p.suggest);
    if (!dish) throw new Error(`${where}: no dish with slug "${p.suggest}" on the menu`);
    if (dish.section.id === section.id) throw new Error(`${where}: suggests a dish from its own section`);
    if (!TYPES.has(p.type)) throw new Error(`${where}: type "${p.type}" is not one of ${[...TYPES].join(', ')}`);
    if (!Number.isInteger(p.priority) || p.priority < 0 || p.priority > 100) throw new Error(`${where}: priority must be 0–100`);
    return { p, section, dish };
  });

  const values = rows.map(({ p, section, dish }, i) =>
    `    ('${p.id}', '${section.id}', '${dish.id}', '${p.type}', ${p.priority})${i < rows.length - 1 ? ',' : ' '}`
    + `  -- ${comment(section.name)} → ${comment(dish.name)}: ${comment(p.why ?? '')}`);

  return [
    BEGIN,
    `-- ${rows.length} pairings. A dish or section deleted in the admin since is skipped,`,
    '-- and a rule already there (by id) is left as the owner has it.',
    'INSERT INTO public.menu_item_recommendations',
    '       (id, source_subcategory_id, recommended_item_id, recommendation_type, priority)',
    'SELECT v.id::uuid, v.section::uuid, v.dish::uuid, v.kind, v.priority::smallint',
    '  FROM (VALUES',
    ...values,
    '  ) AS v(id, section, dish, kind, priority)',
    ' WHERE EXISTS (SELECT 1 FROM public.subcategories s WHERE s.id = v.section::uuid)',
    '   AND EXISTS (SELECT 1 FROM public.menu_items mi WHERE mi.id = v.dish::uuid)',
    'ON CONFLICT (id) DO NOTHING;',
    END,
  ].join('\n');
}

/** Replace the generated block of the migration with what menu.json says now. */
function main() {
  const menu = JSON.parse(readFileSync(join(HERE, 'menu.json'), 'utf8'));
  const text = readFileSync(MIGRATION, 'utf8');
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const flat = text.replace(/\r\n/g, '\n');
  const from = flat.indexOf(BEGIN);
  const to = flat.indexOf(END, from);
  if (from < 0 || to < 0) throw new Error(`no generated block (${BEGIN} … ${END}) in ${MIGRATION}`);
  const next = flat.slice(0, from) + pairingsSql(menu) + flat.slice(to + END.length);
  writeFileSync(MIGRATION, next.replace(/\n/g, eol));
  console.log(`wrote ${menu.pairings.length} pairings to ${MIGRATION.slice(ROOT.length + 1)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
