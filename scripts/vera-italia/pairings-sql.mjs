#!/usr/bin/env node
/**
 * Vera Italia's house pairings as SQL.
 *
 *   node scripts/vera-italia/pairings-sql.mjs
 *
 * The pairings are kept in menu.json beside this file, under "pairings": a
 * section of the menu, the dish (by slug) a waiter would suggest with it, the
 * kind of suggestion, a priority (0–100) and why. menu.json stays the one
 * place Vera Italia's dishes are written down; this turns its pairings into
 * the generated block of supabase/migrations/20261031090000_vera_suggestions.sql,
 * by fixed id only — La Soul has sections and dishes of the same names, so
 * nothing is ever looked up by name in the database.
 *
 * That migration is applied, so its block is frozen: it is generated from each
 * pairing's "seeded" values where a pairing has them (what was first written
 * there), and supabase/tests/vera-suggestions.test.ts fails if it no longer
 * matches. A pairing changed since keeps its first values under "seeded" and
 * its new ones on the pairing; running this writes the changes, as UPDATEs
 * guarded on the seeded priority, into the generated block of
 * supabase/migrations/20261031120000_reco_quality.sql — a rule the owner has
 * since edited in Admin → Service & suggestions is left as they have it.
 * A pairing added from here on needs an insert of its own in a new migration.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
export const MIGRATION = join(ROOT, 'supabase', 'migrations', '20261031090000_vera_suggestions.sql');
export const BEGIN = '-- BEGIN GENERATED by scripts/vera-italia/pairings-sql.mjs from scripts/vera-italia/menu.json';
export const END = '-- END GENERATED';
/** Where changes to the pairings since MIGRATION are written. */
export const UPDATES_MIGRATION = join(ROOT, 'supabase', 'migrations', '20261031120000_reco_quality.sql');
export const UPDATES_BEGIN = '-- BEGIN GENERATED UPDATES by scripts/vera-italia/pairings-sql.mjs from scripts/vera-italia/menu.json';
export const UPDATES_END = '-- END GENERATED UPDATES';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
/** What a pairing may be; 'after_meal' needs no section and 'alternative' is not a pairing. */
const TYPES = new Set(['pair_with', 'add_on', 'upgrade_to']);

/** A comment may say anything but end itself early. */
const comment = (s) => String(s).replace(/[\r\n]+/g, ' ');

/** Every pairing in `menu`, checked against the menu, with its section and dish. */
function checkedPairings(menu) {
  const sections = new Map();
  const dishes = new Map();
  for (const c of menu.categories) {
    for (const s of c.sections) {
      if (sections.has(s.name)) throw new Error(`two sections named "${s.name}" in menu.json`);
      sections.set(s.name, s);
      for (const it of s.items) dishes.set(it.slug, { ...it, section: s });
    }
  }

  const seen = new Set();
  return (menu.pairings ?? []).map((p) => {
    const where = `pairing ${p.id ?? '(no id)'}`;
    if (!UUID.test(p.id ?? '') || seen.has(p.id)) throw new Error(`${where}: needs its own fixed id`);
    seen.add(p.id);
    const section = sections.get(p.with);
    if (!section) throw new Error(`${where}: no section "${p.with}" on the menu`);
    const dish = dishes.get(p.suggest);
    if (!dish) throw new Error(`${where}: no dish with slug "${p.suggest}" on the menu`);
    if (dish.section.id === section.id) throw new Error(`${where}: suggests a dish from its own section`);
    if (!TYPES.has(p.type)) throw new Error(`${where}: type "${p.type}" is not one of ${[...TYPES].join(', ')}`);
    for (const priority of [p.priority, ...(p.seeded ? [p.seeded.priority] : [])]) {
      if (!Number.isInteger(priority) || priority < 0 || priority > 100) throw new Error(`${where}: priority must be 0–100`);
    }
    return { p, section, dish };
  });
}

/** A pairing as MIGRATION first wrote it: its "seeded" values where it has them. */
const asSeeded = (p) => ({ ...p, priority: p.seeded?.priority ?? p.priority, why: p.seeded?.why ?? p.why });

/** The generated block, BEGIN to END, for the pairings in `menu` as MIGRATION first wrote them. */
export function pairingsSql(menu) {
  const rows = checkedPairings(menu).map((r) => ({ ...r, p: asSeeded(r.p) }));
  const values = rows.map(({ p, section, dish }, i) =>
    `    ('${p.id}', '${section.id}', '${dish.id}', '${p.type}', ${p.priority})${i < rows.length - 1 ? ',' : ' '}`
    + `  -- ${comment(section.name)} → ${comment(dish.name)}: ${comment(p.why ?? '')}`);

  return [
    BEGIN,
    `-- ${rows.length} pairings. A dish or section deleted in the admin since is skipped,`,
    '-- and a rule already there (by id) is left as the owner has it.',
    'INSERT INTO public.menu_item_recommendations',
    '       (id, source_subcategory_id, recommended_item_id, recommendation_type, priority)',
    'SELECT v.id::uuid, v.section::uuid, v.dish::uuid, v.kind, v.priority::smallint',
    '  FROM (VALUES',
    ...values,
    '  ) AS v(id, section, dish, kind, priority)',
    ' WHERE EXISTS (SELECT 1 FROM public.subcategories s WHERE s.id = v.section::uuid)',
    '   AND EXISTS (SELECT 1 FROM public.menu_items mi WHERE mi.id = v.dish::uuid)',
    'ON CONFLICT (id) DO NOTHING;',
    END,
  ].join('\n');
}

/**
 * The generated UPDATES block, UPDATES_BEGIN to UPDATES_END: each pairing
 * changed since MIGRATION moves from its seeded priority to its new one, and
 * only while it still has the seeded one.
 */
export function pairingUpdatesSql(menu) {
  const rows = checkedPairings(menu).filter(({ p }) => p.seeded && p.seeded.priority !== p.priority);
  const values = rows.map(({ p, section, dish }, i) =>
    `    ('${p.id}', ${p.seeded.priority}, ${p.priority})${i < rows.length - 1 ? ',' : ' '}`
    + `  -- ${comment(section.name)} → ${comment(dish.name)}: ${comment(p.why ?? '')}`);
  return [
    UPDATES_BEGIN,
    `-- ${rows.length} pairing${rows.length === 1 ? '' : 's'} changed since 20261031090000_vera_suggestions.sql. Each moves`,
    '-- only while it still has the priority first written there: a rule the',
    '-- owner has edited in the admin is left as they have it.',
    ...(rows.length ? [
      'UPDATE public.menu_item_recommendations r',
      '   SET priority = v.priority::smallint',
      '  FROM (VALUES',
      ...values,
      '  ) AS v(id, seeded, priority)',
      ' WHERE r.id = v.id::uuid AND r.priority = v.seeded::smallint;',
    ] : []),
    UPDATES_END,
  ].join('\n');
}

/** Replace the block between `begin` and `end` of `file` with `block`. */
function writeBlock(file, begin, end, block) {
  const text = readFileSync(file, 'utf8');
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const flat = text.replace(/\r\n/g, '\n');
  const from = flat.indexOf(begin);
  const to = flat.indexOf(end, from);
  if (from < 0 || to < 0) throw new Error(`no generated block (${begin} … ${end}) in ${file}`);
  writeFileSync(file, (flat.slice(0, from) + block + flat.slice(to + end.length)).replace(/\n/g, eol));
}

/**
 * Write what menu.json says now: the changes go into UPDATES_MIGRATION; the
 * applied MIGRATION is only checked, never rewritten.
 */
function main() {
  const menu = JSON.parse(readFileSync(join(HERE, 'menu.json'), 'utf8'));
  if (!readFileSync(MIGRATION, 'utf8').replace(/\r\n/g, '\n').includes(pairingsSql(menu))) {
    throw new Error(`${MIGRATION.slice(ROOT.length + 1)} is applied: change a pairing with "seeded" values in menu.json, never in place`);
  }
  writeBlock(UPDATES_MIGRATION, UPDATES_BEGIN, UPDATES_END, pairingUpdatesSql(menu));
  console.log(`wrote the changed pairings to ${UPDATES_MIGRATION.slice(ROOT.length + 1)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main();
