#!/usr/bin/env node
/**
 * Vera Italia's menu as a migration.
 *
 *   node scripts/vera-italia/menu-sql.mjs
 *
 * menu.json beside this file is the menu as the owner sent it (names,
 * descriptions in three languages, prices, allergens); this writes it to
 * supabase/migrations/20261030120000_vera_italia_menu.sql. Every row has a
 * fixed id, so the photos (public/menu/<id>/) and the tests can name a dish,
 * and inserting twice changes nothing. Edit menu.json and run this again
 * only while the migration is unapplied; once it is live, changes go through
 * Admin → Menu or a new migration.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..', '..');
const OUT = join(ROOT, 'supabase', 'migrations', '20261030120000_vera_italia_menu.sql');
const menu = JSON.parse(readFileSync(join(HERE, 'menu.json'), 'utf8'));

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a?.length ? `ARRAY[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const num = (n) => Number(n).toFixed(2);

/** Where the app serves a dish's photo (scripts/fetch-images.mjs writes it). */
export const imageUrl = (id) => `/menu/${id}/1152.webp`;

const categories = [];
const sections = [];
const items = [];
for (const c of menu.categories) {
  categories.push(`  (${q(c.id)}, ${q(c.name)}, ${q(c.name_bs)}, ${q(c.name_ar)}, ${c.sort_order}, ${q(menu.venue_id)})`);
  for (const s of c.sections) {
    sections.push(`  (${q(s.id)}, ${q(c.id)}, ${q(s.name)}, ${q(s.name_bs)}, ${q(s.name_ar)}, ${s.sort_order})`);
    s.items.forEach((it, i) => {
      items.push(`  (${[
        q(it.id), q(s.id), q(it.name), q(it.name_bs), q(it.name_ar),
        q(it.description), q(it.description_bs), q(it.description_ar),
        num(it.price), 'true', q(it.station ?? 'kitchen'), arr(it.allergens), arr(it.dietary_tags),
        `${q(it.meal_role)}::public.meal_role`, i + 1, it.no_photo ? 'NULL' : q(imageUrl(it.id)),
        it.featured_rank ?? 'NULL', q(it.featured_note), q(it.featured_note_bs), q(it.featured_note_ar),
      ].join(', ')})`);
    });
  }
}

const sql = `-- =====================================================================
-- Vera Italia's menu (docs/two-restaurants.md, phase 4)
-- =====================================================================
-- GENERATED by scripts/vera-italia/menu-sql.mjs from
-- scripts/vera-italia/menu.json — edit those, not this file.
--
-- ${menu.categories.length} courses, ${sections.length} sections, ${items.length} dishes, every one Vera Italia's
-- (${menu.venue_id}). Sections and dishes take their restaurant from their
-- course. Fixed ids: inserting again changes nothing, and nothing here
-- touches La Soul. Vera Italia stays not live; switching it on is its own
-- step (docs/two-restaurants-rollout.md).
--
-- ${menu.source}

INSERT INTO public.categories (id, name, name_bs, name_ar, sort_order, venue_id) VALUES
${categories.join(',\n')}
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.subcategories (id, category_id, name, name_bs, name_ar, sort_order) VALUES
${sections.join(',\n')}
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.menu_items (
  id, subcategory_id, name, name_bs, name_ar,
  description, description_bs, description_ar,
  price, is_available, station, allergens, dietary_tags,
  meal_role, sort_order, image_url,
  featured_rank, featured_note, featured_note_bs, featured_note_ar
) VALUES
${items.join(',\n')}
ON CONFLICT (id) DO NOTHING;
`;

writeFileSync(OUT, sql);
console.log(`wrote ${items.length} dishes to ${OUT.slice(ROOT.length + 1)}`);
